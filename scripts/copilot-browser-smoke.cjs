const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 try {
 const page=await browser.newPage({viewport:{width:1480,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.MARS_ATLAS_URL || 'http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
 await page.locator('button[data-step="all"]').click();
 await page.locator('[data-group="models"]').click();
 await page.locator('#copilot-local').click();
 assert.match(await page.locator('#copilot-output').textContent(),/DETERMINISTIC/);
 await page.locator('[data-copilot-prompt]').first().click();
 assert.match(await page.locator('#copilot-question').inputValue(),/Explain this route/);
 await page.locator('#copilot-ask').click();
 assert.match(await page.locator('#copilot-output').textContent(),/Consent is required/);
 await page.locator('#copilot-consent').check();
 await page.locator('#copilot-ask').click();
 assert.match(await page.locator('#copilot-output').textContent(),/Sign in/);
 await page.locator('#copilot-propose').click();
 assert.match(await page.locator('#copilot-output').textContent(),/Load numeric/);
 await page.locator('[data-action="load-review-demo"]').click();
 await page.locator('button[data-step="all"]').click();
 await page.locator('[data-group="terrain"]').click();
 await page.waitForFunction(()=>!document.querySelector('#terrain-compare').disabled);
 await page.locator('#terrain-grade').evaluate(input=>{input.closest('details').open=true; input.value='100'; input.dispatchEvent(new Event('change',{bubbles:true}));});
 await page.locator('[data-group="models"]').click();
 const routeCount=await page.locator('#route-count').textContent();
 await page.locator('#copilot-propose').click();
 await page.waitForFunction(()=>document.querySelectorAll('#terrain-strategies .strategy-card').length===3);
 assert.equal(await page.locator('#route-count').textContent(),routeCount,'Preview must not add a route');
 await page.locator('[data-group="models"]').click();
 await page.locator('.copilot-section').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/mars-copilot-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-action="show-analytics"]').click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2));
 await page.screenshot({path:'/tmp/mars-copilot-mobile.png'});
 assert.deepEqual(errors,[]);
 await page.evaluate(async () => {
   const {mountMissionCopilot} = await import('/src/mission-copilot-ui.js');
   const panel=document.createElement('div'); document.body.append(panel);
   const before=document.createElement('div'); panel.append(before);
   const callbacks=[];
   const store={current:{id:'test', routes:[{id:'r',points:[]}], activeRouteId:'r', observations:[]}, subscribe(fn){callbacks.push(fn)}};
   const cloud={user:{id:'u'},client:{functions:{invoke(){return new Promise(resolve=>window.resolveCopilot=resolve)}}}};
   const {section}=mountMissionCopilot({panel,before,store,getDem:()=>null,getCloud:()=>cloud,notify:()=>{}});
   section.querySelector('#copilot-consent').checked=true;
   section.querySelector('#copilot-question').value='Explain route';
   section.querySelector('form').dispatchEvent(new Event('submit',{cancelable:true}));
   store.current.id='different'; callbacks.forEach(fn=>fn());
   window.resolveCopilot({data:{answer:'OUTDATED ANSWER'}});
   await new Promise(resolve=>setTimeout(resolve,0));
   if(section.querySelector('#copilot-output').textContent.includes('OUTDATED')) throw Error('Stale AI answer was rendered');
   if(section.querySelector('#copilot-ask').disabled) throw Error('Submit left disabled');
   panel.remove();
 });
 console.log('PASS: local summary, prompts, consent, signed-out error, proposal prerequisites, mobile overflow, no page errors');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
